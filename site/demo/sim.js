  const isNum = (x) => typeof x === "number" && Number.isFinite(x);
  const num = (x, d) => (isNum(x) ? x : (d === undefined ? 0 : d));
  const int = (x) => Math.trunc(num(x));
  const dict = (x) => (x && typeof x === "object" && !Array.isArray(x) ? x : {});
