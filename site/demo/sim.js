  function mulberry32(a) {
    return function () {
      a |= 0; a = (a + 0x6D2B79F5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  const hex = (rng, n) => { let s = ""; while (s.length < n) s += Math.floor(rng() * 16).toString(16); return s; };
  const r1 = (x) => Math.round(x * 10) / 10;
  const pyJson = (o) => "{" + Object.entries(o).map(([k, v]) => JSON.stringify(k) + ": " + (typeof v === "string" ? JSON.stringify(v) : v)).join(", ") + "}";

