    if (parts.length) {
      const s = ["Node B policy decisions so far: " + parts.join(", ") + "."];
      if (int(pol.PENDING_APPROVAL)) s.push("In the default mode a mapped alert never blocks by itself; a person must approve it.");
      sections.push(["Policy decisions", s]);
    }

    const smap = {};
    for (const [k, v] of Object.entries(dict(b.subject_map))) if (ipOf(k) && ipOf(v)) smap[k] = v;
    const pend = list(b.pending_approvals).map(dict).filter((p) => ipOf(p.subject));
