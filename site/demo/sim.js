/* CyberSim: an in-browser stand-in for the two-node demo's /api/* (Node A, Node B, policy gate, enforcer).
 *
 * It exists so the real dashboard page can run on a static host with no server. Everything is GENERATED in the
 * visitor's browser: there is no model, no network traffic and no real gate. It mirrors the demo's rules so the
 * behaviour is faithful, but it proves nothing about detection quality.
 *
 * Rules mirrored from demo/two_node: a mapped alert never blocks by itself; a person approves it; a human block
 * lasts at most 30 s; the opt-in autonomous lab mode allows ONE automatic block per target per process, at most
 * 10 s, no renewal; a newer alert supersedes a pending one (a stale approval is refused with 409); operator
 * endpoints need the X-CyberNCM-Operator header (403 without it); emergency disable releases the rule and turns
 * automation off. Works in a browser (window.CyberSim) and in Node (module.exports) for tests.
 */
