    const accepted = int(counts.alerts_accepted), rejected = int(counts.alerts_rejected);
    const browser = state.simulation === "browser", sandbox = state.sandbox === true;
    const synthetic = browser || sandbox;
    const sections = [];
    let head;

    if (windows === 0 && sent === 0 && accepted === 0) {
      head = "No replay data yet: start the replay to generate a report.";
      sections.push(["Overview", [head]]);
    } else {
      const day = labelOf(replay.day) || "recorded traffic";
      const fmt = labelOf(model.format);
      head = (browser ? "Browser simulation" : sandbox ? "Sandbox replay" : "Recorded replay") + " of " + day + ": " + plural(windows, "window") +
        " scored, " + plural(sent, "signed alert") + " sent, " + accepted + " accepted and " + rejected + " rejected by Node B.";
      const s = [head];
      if (browser) s.push("There is no model in this simulation: the scores are generated numbers.");
      else if (fmt) s.push("The detector ran a " + (sandbox ? "toy" : "frozen") + " " + fmt + " model" + (sandbox ? " trained on synthetic data" : "") + " with no online learning.");
      const step = int(replay.step), total = int(replay.total_steps);
      if (total > 0) s.push("Replay progress: step " + Math.min(step, total) + " of " + total + " (" + Math.min(100, Math.floor(100 * step / total)) + "%).");
      sections.push(["Overview", s]);
    }

    const per = new Map();
    for (let ev of list(b.alert_log)) {
      ev = dict(ev); const ip = ipOf(ev.subject);
      if (!ip) continue;
      if (!per.has(ip)) per.set(ip, { n: 0, peak: 0.0, stage: null });
      const r = per.get(ip);
      r.n += 1; r.peak = Math.max(r.peak, num(ev.risk)); r.stage = r.stage || stageOf(ev.stage);
    }
    const labels = new Map();
    for (let ev of list(a.recent_alerts)) {
      ev = dict(ev); const ip = ipOf(ev.subject), lab = labelOf(ev.dataset_ground_truth_only);
      if (ip && lab) {
        if (!labels.has(ip)) labels.set(ip, lab);
        if (per.has(ip) && !per.get(ip).stage) per.get(ip).stage = stageOf(ev.stage);
      }
    }
    const top = [...per.entries()].sort((x, y) => (y[1].n - x[1].n) || (y[1].peak - x[1].peak) || cmp(x[0], y[0])).slice(0, 3);
    if (top.length) {
      const s = [];
      for (const [ip, r] of top) {
        let bit = ip + ": " + plural(r.n, "alert") + ", peak risk " + r.peak.toFixed(2);
        if (r.stage) bit += ", inferred stage " + r.stage;
        if (labels.has(ip)) {
          bit += " (" + (synthetic ? "synthetic label" : "dataset label") + ", ground truth only: " + labels.get(ip) + ")";
          if (labels.get(ip).toUpperCase() === "BENIGN") bit += ", so by that label this is a false alert";
        }
        s.push(bit + ".");
      }
      sections.push(["Most alerted sources", s]);
    }

    const pol = dict(counts.policy);
