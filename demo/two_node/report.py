"""Plain-language report and summary generated from Node B's structured state.

This is rule-based natural-language generation: fixed sentence templates filled from a short allowlist
of structured fields (counts, scores, validated IP addresses, enumerated labels). It does NOT use a
language model, never reads message text or free-form strings (sender names, reasons, previews), and
cannot influence any decision: it is only called by read-only endpoints. That design is deliberate. The
project's own language-model experiment (research/R14) followed an injected instruction, so no free text
from traffic or messages may reach anything that explains or decides.

    build_report(state) -> {"headline", "sections", "text", "markdown", "facts", "method"}
"""
import ipaddress
import math
import re

METHOD = ("Generated by fixed templates over structured fields. No language model is used, no message text is "
          "read, and the report cannot affect any decision.")
SCOPE_SANDBOX = ("This is a sandbox: synthetic traffic and a toy model on one machine. Nothing here is real data, a real detection, independent corroboration between sites, or a validated mesh. Dataset labels do not exist here; \"truth\" labels are synthetic.")
SCOPE = ("This describes a loopback demonstration on one machine that replays recorded traffic through a frozen "
         "model. It is not a live detection, not independent corroboration between sites, and not evidence of a "
         "validated mesh. Dataset labels are shown for explanation only and are never model output.")

_STAGE = re.compile(r"^[A-Z][A-Z_]{2,31}$")
_LABEL = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 _.\-/()]{0,39}$")
_POLICY_NAMES = {"PENDING_APPROVAL": "awaiting human approval", "BLOCK": "blocks applied",
                 "AUTONOMOUS_BLOCK": "automatic lab blocks applied", "ALREADY_BLOCKED": "already blocked",
                 "REJECT": "rejected"}
_MODES = {"human": "human approval", "human-approved": "human approval", "operator": "human approval",
          "autonomous-lab": "automatic lab mode"}


def _num(x, default=0.0):
    return float(x) if isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x) else default


def _int(x):
    return int(_num(x))


def _ip(x):
    try:
        return str(ipaddress.ip_address(x)) if isinstance(x, str) else None
    except ValueError:
        return None


def _stage(x):
    return x if isinstance(x, str) and _STAGE.match(x) else None


def _label(x):
    return x if isinstance(x, str) and _LABEL.match(x) else None


def _d(x):
    return x if isinstance(x, dict) else {}


def _l(x):
    return x if isinstance(x, list) else []


def _plural(n, one, many=None):
    return f"{n} {one if n == 1 else (many or one + 's')}"


def build_report(state) -> dict:
    state = _d(state)
    a, b = _d(state.get("node_a")), _d(state.get("node_b"))
    replay, link, model = _d(a.get("replay")), _d(a.get("link_to_node_b")), _d(a.get("model"))
    counts = _d(b.get("counts"))
    windows, sent = _int(replay.get("windows_scored")), _int(link.get("alerts_sent"))
    accepted, rejected = _int(counts.get("alerts_accepted")), _int(counts.get("alerts_rejected"))
    facts = {"windows_scored": windows, "alerts_sent": sent, "alerts_accepted": accepted, "alerts_rejected": rejected}
    sandbox = state.get("sandbox") is True
    sections = []

    # 1. Overview
    if windows == 0 and sent == 0 and accepted == 0:
        head = "No replay data yet: start the replay to generate a report."
        sections.append(("Overview", [head]))
    else:
        day = _label(replay.get("day")) or "recorded traffic"
        fmt = _label(model.get("format"))
        head = (f"{'Sandbox replay' if sandbox else 'Recorded replay'} of {day}: {_plural(windows, 'window')} scored, {_plural(sent, 'signed alert')} sent, "
                f"{accepted} accepted and {rejected} rejected by Node B.")
        s = [head]
        if fmt:
            s.append(f"The detector ran a {'toy' if sandbox else 'frozen'} {fmt} model{' trained on synthetic data' if sandbox else ''} with no online learning.")
        step, total = _int(replay.get("step")), _int(replay.get("total_steps"))
        if total > 0:
            s.append(f"Replay progress: step {min(step, total)} of {total} ({min(100, 100 * step // total)}%).")
        sections.append(("Overview", s))

    # 2. Most alerted sources (validated IPs only; dataset labels labelled as ground truth)
    per = {}
    for ev in _l(b.get("alert_log")):
        ev = _d(ev); ip = _ip(ev.get("subject"))
        if not ip:
            continue
        r = per.setdefault(ip, {"n": 0, "peak": 0.0, "stage": None})
        r["n"] += 1; r["peak"] = max(r["peak"], _num(ev.get("risk")))
        r["stage"] = r["stage"] or _stage(ev.get("stage"))
    labels = {}
    for ev in _l(a.get("recent_alerts")):
        ev = _d(ev); ip = _ip(ev.get("subject")); lab = _label(ev.get("dataset_ground_truth_only"))
        if ip and lab:
            labels.setdefault(ip, lab)
            if ip in per and not per[ip]["stage"]:
                per[ip]["stage"] = _stage(ev.get("stage"))
    top = sorted(per.items(), key=lambda kv: (-kv[1]["n"], -kv[1]["peak"], kv[0]))[:3]
    facts["top_sources"] = [{"source": ip, "alerts": r["n"], "peak_risk": round(r["peak"], 2)} for ip, r in top]
    if top:
        s = []
        for ip, r in top:
            bit = f"{ip}: {_plural(r['n'], 'alert')}, peak risk {r['peak']:.2f}"
            if r["stage"]:
                bit += f", inferred stage {r['stage']}"
            if ip in labels:
                bit += f" ({'synthetic label' if sandbox else 'dataset label'}, ground truth only: {labels[ip]})"
                if labels[ip].upper() == "BENIGN":
                    bit += ", so by that label this is a false alert"
            s.append(bit + ".")
        sections.append(("Most alerted sources", s))

    # 3. Policy decisions
    pol = _d(counts.get("policy"))
    parts = [f"{_int(pol.get(k))} {txt}" for k, txt in _POLICY_NAMES.items() if _int(pol.get(k)) > 0]
    facts["policy"] = {k: _int(pol.get(k)) for k in _POLICY_NAMES}
    if parts:
        s = ["Node B policy decisions so far: " + ", ".join(parts) + "."]
        if _int(pol.get("PENDING_APPROVAL")):
            s.append("In the default mode a mapped alert never blocks by itself; a person must approve it.")
        sections.append(("Policy decisions", s))

    # 4. Pending approvals and active blocks
    smap = {k: v for k, v in _d(b.get("subject_map")).items() if _ip(k) and _ip(v)}
    pend = [p for p in (_d(x) for x in _l(b.get("pending_approvals"))) if _ip(p.get("subject"))]
    blocks = [x for x in (_d(y) for y in _l(b.get("active_blocks"))) if _ip(x.get("target") or x.get("ip"))]
    facts["pending_approvals"], facts["active_blocks"] = len(pend), len(blocks)
    s = []
    if pend:
        subs = sorted({_ip(p["subject"]) for p in pend})
        tg = sorted({smap[x] for x in subs if x in smap})
        s.append(f"{_plural(len(pend), 'directive')} awaiting approval for {', '.join(subs)}"
                 + (f" (mapped to lab client {', '.join(tg)})." if tg else "."))
    if blocks:
        for bl in blocks:
            tgt = _ip(bl.get("target") or bl.get("ip"))
            mode = _MODES.get(bl.get("approval_mode"), "an approved action")
            ttl = _num(bl.get("ttl"), -1)
            s.append(f"{tgt} is blocked by {mode}" + (f" for at most {ttl:.0f} seconds." if ttl >= 0 else "."))
    elif windows or sent:
        s.append("No block is active.")
    if s:
        sections.append(("Approvals and blocks", s))

    # 5. Enforcement evidence
    ps = _d(b.get("probe_summary"))
    lab, ctl = _d(ps.get("latest_lab")), _d(ps.get("latest_control"))
    s = []
    if "ok" in lab and "ok" in ctl:
        s.append(f"Latest probes: the lab client was {'reachable' if lab.get('ok') is True else 'blocked or unreachable'} "
                 f"and the control client was {'reachable' if ctl.get('ok') is True else 'blocked or unreachable'}.")
    drops = _int(b.get("drops_total"))
    if drops:
        s.append(f"The userspace gate dropped {_plural(drops, 'request')} from the blocked client.")
    ev_types = {}
    for e in _l(b.get("enforcer_events")):
        t = _d(e).get("type")
        if t in ("block_applied", "block_expired", "block_released"):
            ev_types[t] = ev_types.get(t, 0) + 1
    if ev_types:
        s.append("Enforcement events recorded: " + ", ".join(f"{v} {k.replace('_', ' ')}" for k, v in sorted(ev_types.items())) + ".")
    facts["drops_total"] = drops
    if s:
        sections.append(("Enforcement evidence", s))

    # 6. Autonomy
    auto = b.get("autonomous_lab") is True
    used = len(_l(b.get("autonomous_targets_used")))
    secs = _int(b.get("automatic_block_seconds")) or 10
    sections.append(("Automation", [
        (f"Autonomous lab mode is ON: at most one automatic block per allowlisted target per process, lasting at most {secs} seconds, "
         f"with no automatic renewal ({used} used)." if auto else
         "Autonomous lab mode is OFF: every block needs explicit human approval.")]))
    facts["autonomous_lab"] = auto

    # 7. Fixed caveats
    sections.append(("How to read this report", [METHOD, SCOPE_SANDBOX if sandbox else SCOPE]))

    text = head + "\n\n" + "\n\n".join(f"{t}\n" + "\n".join(f"- {x}" for x in ss) for t, ss in sections)
    md = "# Demo report\n\n" + "\n\n".join(f"## {t}\n\n" + "\n".join(f"- {x}" for x in ss) for t, ss in sections) + "\n"
    return {"headline": head, "sections": [{"title": t, "sentences": ss} for t, ss in sections],
            "text": text, "markdown": md, "facts": facts, "method": METHOD}
